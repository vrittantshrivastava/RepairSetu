export function getStoresWithDistances(userLat: number, userLng: number): NearbyRepairStore[] {
  return BASE_NEARBY_STORES.map((store) => {
    const priceRange = store.priceRange || (store.startingPrice < 500 ? '₹' : store.startingPrice < 800 ? '₹₹' : '₹₹₹');
    return {
      ...store,
      priceRange,
      distanceKm: calculateDistanceKm(userLat, userLng, store.latitude, store.longitude),
    };
  }).sort((a, b) => a.distanceKm - b.distanceKm);
}
